package com.example.propertyview.entity;

import jakarta.persistence.*;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;
import java.util.LinkedHashSet;
import java.util.Set;

/**
 * Represents a hotel stored in the hotels table.
 * Contains hotel information, address, contacts, arrival times and amenities.
 */
@Entity
@Table(name = "hotels")
@Getter // Generates getter methods for all fields.
@Setter // Generates setter methods for all fields.
@NoArgsConstructor // Generates the no-argument constructor required by JPA.
public class Hotel {

    // Primary key generated by the database using an identity column.
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    // Required hotel name.
    @Column(nullable = false)
    private String name;

    // Optional hotel description, up to 10,000 characters.
    @Column(length = 10000)
    private String description;

    // Required hotel brand.
    @Column(nullable = false)
    private String brand;

    // Address fields are stored directly in the hotels table.
    @Column(name = "house_number", nullable = false)
    private Integer houseNumber;

    @Column(nullable = false)
    private String street;

    @Column(nullable = false)
    private String city;

    @Column(nullable = false)
    private String country;

    // Stored as text to preserve leading zeros.
    @Column(name = "post_code", nullable = false, length = 32)
    private String postCode;

    // Required contact details.
    @Column(nullable = false, length = 64)
    private String phone;

    @Column(nullable = false, length = 254)
    private String email;

    // Required check-in time stored as a five-character HH:mm string.
    @Column(name = "check_in", nullable = false, length = 5)
    private String checkIn;

    // Optional check-out time stored in the same format.
    @Column(name = "check_out", length = 5)
    private String checkOut;

    /**
     * Stores amenities in a separate hotel_amenities table.
     * Each row references this hotel through hotel_id.
     * The unique constraint prevents duplicate hotel/amenity pairs.
     * Amenities are loaded lazily and ordered by their string values.
     */
    @ElementCollection(fetch = FetchType.LAZY)
    @CollectionTable(
            name = "hotel_amenities",
            joinColumns = @JoinColumn(name = "hotel_id"),
            uniqueConstraints = @UniqueConstraint(columnNames = {"hotel_id", "amenity"})
    )
    @Column(name = "amenity", nullable = false, length = 255)
    @OrderBy
    private Set<String> amenities = new LinkedHashSet<>();
}